const generatedMarker = "<!-- DO NOT EDIT: generated by projectctl docs generate. -->"

type generatedDocument struct {
	path string
	data []byte
}

func (a *App) docsCommand(args []string) error {
	if len(args) != 1 {
		return usageError("docs generate|check")
	}
	switch args[0] {
	case "generate":
		return a.generateDocuments()
	case "check":
		return a.checkDocuments()
	default:
		return usageError("docs generate|check")
	}
}

func (a *App) generatedDocuments() ([]generatedDocument, error) {
	decisions, requirements, tests, trace, err := a.loadAuthority()
	if err != nil {
		return nil, err
	}
	if err := validateDecisions(decisions); err != nil {
		return nil, err
	}
	if err := a.validateTraceability(decisions, requirements, tests, trace); err != nil {
		return nil, err
	}

	return []generatedDocument{
		{path: "docs/70-decisions/DECISION_INDEX.md", data: generateDecisionIndex(decisions)},
		{path: "docs/70-decisions/SUPERSESSION_MAP.md", data: generateSupersessionMap(decisions)},
		{path: "docs/90-traceability/TRACEABILITY.md", data: generateTraceabilityIndex(requirements, tests, trace)},
	}, nil
}

func (a *App) generateDocuments() error {
	documents, err := a.generatedDocuments()
	if err != nil {
		return err
	}
	for _, document := range documents {
		if err := atomicWrite(filepath.Join(a.root, filepath.FromSlash(document.path)), document.data, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", document.path, err)
		}
		fmt.Fprintf(a.stdout, "[GENERATED] %s\n", document.path)
	}
	return nil
}

func (a *App) checkDocuments() error {
	documents, err := a.generatedDocuments()
	if err != nil {
		return err
	}
	var drift []string
	for _, document := range documents {
		actual, readErr := os.ReadFile(filepath.Join(a.root, filepath.FromSlash(document.path)))
		if readErr != nil || !bytes.Equal(actual, document.data) {
			drift = append(drift, document.path)
		}
	}
	if len(drift) != 0 {
		return fmt.Errorf("generated documentation drift: %s; run projectctl docs generate", strings.Join(drift, ", "))
	}
	fmt.Fprintln(a.stdout, "[PASS] generated documentation is current")
	return nil
}

func atomicWrite(path string, data []byte, mode os.FileMode) error {
	temporary, err := os.CreateTemp(filepath.Dir(path), ".projectctl-generated-*")
	if err != nil {
		return err
	}
	temporaryName := temporary.Name()
	defer os.Remove(temporaryName)
	if err := temporary.Chmod(mode); err != nil {
		temporary.Close()
		return err
	}
	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(temporaryName, path)
}

func generateDecisionIndex(register decisionRegister) []byte {
	var output strings.Builder
	output.WriteString("---\ndocument_id: DECISION-INDEX\nauthority: generated-reference\nstatus: ACTIVE\nsource: DECISION_REGISTER.yaml\n---\n\n")
	output.WriteString(generatedMarker + "\n\n# R0—R24 决策索引\n\n")
	output.WriteString("> 权威机器来源为 `DECISION_REGISTER.yaml`。\n\n")

	statusCounts := map[string]int{}
	for _, item := range register.Decisions {
		statusCounts[item.Status]++
	}
	fmt.Fprintf(&output, "- 决策总数：**%d**\n", len(register.Decisions))
	fmt.Fprintf(&output, "- ACTIVE：**%d**\n", statusCounts["ACTIVE"])
	fmt.Fprintf(&output, "- SUPERSEDED：**%d**\n", statusCounts["SUPERSEDED"])
	fmt.Fprintf(&output, "- 基线状态：**%s**\n", cleanInline(register.BaselineStatus))
	fmt.Fprintf(&output, "- 权威语言：%s\n", cleanInline(register.AuthoritativeLanguage))

	stageOrder := make([]string, 0)
	byStage := map[string][]decision{}
	for _, item := range register.Decisions {
		if _, exists := byStage[item.SourceStage]; !exists {
			stageOrder = append(stageOrder, item.SourceStage)
		}
		byStage[item.SourceStage] = append(byStage[item.SourceStage], item)
	}
	for _, stage := range stageOrder {
		fmt.Fprintf(&output, "\n## %s\n\n", cleanInline(stage))
		output.WriteString("| 决策 ID | 状态 | 标题 | 范围 | 结论 |\n|---|---|---|---|---|\n")
		for _, item := range byStage[stage] {
			fmt.Fprintf(&output, "| `%s` | `%s` | %s | `%s` | %s |\n",
				cleanInline(item.ID), cleanInline(item.Status), cleanInline(item.Title),
				cleanInline(item.Scope), cleanInline(item.Statement))
		}
	}
	return []byte(output.String())
}

