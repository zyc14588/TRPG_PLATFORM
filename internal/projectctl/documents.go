func generateTraceabilityIndex(requirements requirementsDocument, tests testCatalog, trace traceabilityDocument) []byte {
	testsByID := make(map[string]testCase, len(tests.Tests))
	for _, item := range tests.Tests {
		testsByID[item.ID] = item
	}
	mappings := make(map[string]traceMapping, len(trace.Mappings))
	for _, item := range trace.Mappings {
		mappings[item.RequirementID] = item
	}

	var output strings.Builder
	output.WriteString("---\ndocument_id: TRACEABILITY-INDEX\nauthority: generated-reference\nstatus: ACTIVE\nsource:\n- REQUIREMENTS.yaml\n- TEST_CATALOG.yaml\n- TRACEABILITY.yaml\n---\n\n")
	output.WriteString(generatedMarker + "\n\n# 需求—规范—测试追踪索引\n\n")
	fmt.Fprintf(&output, "- 要求：%d\n- 计划测试：%d\n\n", len(requirements.Requirements), len(tests.Tests))
	output.WriteString("| 要求 | 标题 | 规范 | 里程碑 | 测试 | 状态 |\n|---|---|---|---|---|---|\n")
	for _, requirement := range requirements.Requirements {
		mapping := mappings[requirement.ID]
		testLabels := make([]string, 0, len(mapping.TestIDs))
		for _, id := range mapping.TestIDs {
			if _, exists := testsByID[id]; exists {
				testLabels = append(testLabels, "`"+cleanInline(id)+"`")
			}
		}
		fmt.Fprintf(&output, "| `%s` | %s | `%s` | `%s` | %s | `%s` |\n",
			cleanInline(requirement.ID), cleanInline(requirement.Title), cleanInline(mapping.OwningSpec),
			cleanInline(mapping.Milestone), strings.Join(testLabels, "<br>"), cleanInline(mapping.ImplementationStatus))
	}
	return []byte(output.String())
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
